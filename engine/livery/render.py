"""main.typ generation and Typst compilation."""
from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from .tools import REPO_ROOT, TEMPLATE_DIR, require_tools, run

FONT_DIR = TEMPLATE_DIR / "assets" / "fonts"


def template_dir_for(theme_path: Path) -> Path:
    """The template a theme belongs to: the folder holding it when that folder has a
    template.typ (a project-local template, as the desktop app keeps one per design
    revision), otherwise the repository's template/."""
    here = Path(theme_path).resolve().parent
    return here if (here / "template.typ").is_file() else TEMPLATE_DIR


def compute_root(out_dir: Path, theme_path: Path) -> Path:
    """Typst --root must contain the template, the theme and the output folder. With a
    project-local template that is their common folder, not the repository."""
    tdir = template_dir_for(theme_path)
    anchor = REPO_ROOT if tdir == TEMPLATE_DIR else tdir
    return Path(os.path.commonpath([anchor.resolve(), out_dir.resolve(), Path(theme_path).resolve()]))


def root_relative(path: Path, root: Path) -> str:
    return "/" + path.resolve().relative_to(root).as_posix()


def _typst_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def template_import_path(root: Path, theme_path: Path | None = None) -> str:
    tdir = template_dir_for(theme_path) if theme_path is not None else TEMPLATE_DIR
    return root_relative(tdir / "template.typ", root)


def relocate_main(main: Path, old_import: str, root: Path, theme_path: Path | None = None) -> str:
    """If an output folder was moved, the root-relative template import in
    main.typ must follow. Only that string is touched; hand edits survive."""
    new_import = template_import_path(root, theme_path)
    if new_import != old_import and main.exists():
        main.write_text(main.read_text(encoding="utf-8").replace(_typst_str(old_import), _typst_str(new_import)),
                        encoding="utf-8")
    return new_import


def write_main(out_dir: Path, *, title: str, root: Path,
               department: str | None = None, number: str | None = None,
               department_name: str | None = None, version: str | None = None,
               cover: str | None = None, theme_path: Path | None = None) -> Path:
    template_rel = template_import_path(root, theme_path)
    main = out_dir / "main.typ"
    dept_line = f"  department: {_typst_str(department)},\n" if department is not None else ""
    if number is not None:
        dept_line += f"  number: {_typst_str(number)},\n"
    if department_name is not None:
        dept_line += f"  department_name: {_typst_str(department_name)},\n"
    if version is not None:
        dept_line += f"  version: {_typst_str(version)},\n"
    if cover is not None:
        dept_line += f"  cover: {_typst_str(cover)},\n"
    main.write_text(
        "// Generated by livery. Edit content.typ for content, template/theme.toml for looks.\n"
        f"#import {_typst_str(template_rel)}: project\n"
        "#show: project.with(\n"
        f"  title: {_typst_str(title)},\n"
        f"{dept_line}"
        ")\n"
        '#include "content.typ"\n',
        encoding="utf-8",
    )
    return main


@dataclass
class RenderResult:
    pdf: Path
    ok: bool
    warnings: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    stderr: str = ""

    @property
    def font_warnings(self) -> list[str]:
        return [w for w in self.warnings if "unknown font family" in w]


_DIAG_RE = re.compile(r"^(?:(?P<loc>[^:\n]+:\d+:\d+): )?(?P<kind>warning|error): (?P<msg>.*)$")


def typst_command(subcommand: str, main: Path, pdf: Path, *, root: Path, theme_path: Path,
                  verify: bool = False) -> list[str | Path]:
    """The typst invocation used for a document (shared by compile and watch)."""
    tools = require_tools("typst")
    cmd: list[str | Path] = [
        tools["typst"], subcommand,
        "--root", root,
        "--diagnostic-format", "short",
        "--input", f"theme={root_relative(theme_path, root)}",
    ]
    if verify:
        cmd += ["--input", "verify=true"]
    fills = main.parent / "table-fills.json"
    if fills.exists():
        cmd += ["--input", f"fills={root_relative(fills, root)}"]
    # The desktop app's per-document design (treatments and element overrides, resolved
    # for this document) sits next to main.typ.
    design = main.parent / "design.json"
    if design.exists():
        cmd += ["--input", f"design={root_relative(design, root)}"]
    font_dir = template_dir_for(theme_path) / "assets" / "fonts"
    if font_dir.is_dir():
        cmd += ["--font-path", font_dir]
    if os.environ.get("LIVERY_IGNORE_SYSTEM_FONTS") == "1":
        # Reproducible output: only the fonts Typst embeds and the template ships.
        cmd += ["--ignore-system-fonts"]
    cmd += [main, pdf]
    return cmd


# Set by an embedding application to run every Typst compile in a sandbox:
# wrapper(cmd, root, theme_path) -> the command to run instead.
COMMAND_WRAPPER: Callable[[list[str | Path], Path, Path], list[str | Path]] | None = None


def compile_pdf(main: Path, pdf: Path, *, root: Path, theme_path: Path, verify: bool = False) -> RenderResult:
    cmd = typst_command("compile", main, pdf, root=root, theme_path=theme_path, verify=verify)
    if COMMAND_WRAPPER is not None:
        cmd = COMMAND_WRAPPER(cmd, root, theme_path)
    r = run(cmd, check=False)
    warnings: list[str] = []
    errors: list[str] = []
    for line in r.stderr.splitlines():
        m = _DIAG_RE.match(line.strip())
        if not m:
            continue
        text = f"{m.group('loc') + ': ' if m.group('loc') else ''}{m.group('msg')}"
        (warnings if m.group("kind") == "warning" else errors).append(text)
    if not r.ok and not errors:
        errors.append(r.stderr.strip() or f"typst exited with {r.returncode}")
    return RenderResult(pdf=pdf, ok=r.ok and pdf.exists(), warnings=warnings, errors=errors, stderr=r.stderr)
